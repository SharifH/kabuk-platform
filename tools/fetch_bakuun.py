#!/usr/bin/env python3
"""
Refresh assets/data/bakuun-integrations.json from Bakuun's public integrations page
(standard library only). Run from the site root, review the diff, then `python3 tools/build.py`.

    python3 tools/fetch_bakuun.py
    python3 tools/fetch_bakuun.py page1.html page2.html ...   # parse pages saved with curl instead

If Python reports CERTIFICATE_VERIFY_FAILED (python.org builds on macOS ship without CA
certificates), run "Install Certificates.command" from the Python folder, or save the pages with
curl and pass them as arguments:
    for n in 1 2 3; do curl -s "https://www.bakuun.com/integrations?baaa1da9_page=$n" -o bakuun-$n.html; done

Bakuun renders both status labels on every card and hides the one that does not apply
(class "w-condition-invisible"), so only visible labels are kept. Entries whose visible
status or partner type is missing or ambiguous are kept as reported and listed in "_review".
"""
import datetime
import html.parser
import json
import os
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = "https://www.bakuun.com/integrations"
OUT = os.path.join(ROOT, "assets", "data", "bakuun-integrations.json")
STATUS = {"Live": "live", "In Development": "development"}
TYPE = {"Premium Partner": "premium", "Connectivity Partner": "connectivity"}
VOID = {"img", "br", "hr", "input", "meta", "link", "source", "wbr"}


class Cards(html.parser.HTMLParser):
    def __init__(self):
        super().__init__()
        self.stack, self.items, self.cur, self.field = [], [], None, None

    def handle_starttag(self, tag, attrs):
        if tag in VOID:
            return
        a = dict(attrs)
        cls = (a.get("class") or "").split()
        hidden = "w-condition-invisible" in cls or bool(self.stack and self.stack[-1]["hidden"])
        node = {"cls": cls, "hidden": hidden, "item": False, "field": None}
        if "w-dyn-item" in cls and any("intigration-list" in s["cls"] for s in self.stack):
            self.cur = {"name": "", "types": [], "statuses": []}
            node["item"] = True
        elif self.cur is not None and not hidden:
            if "integration-name" in cls:
                node["field"] = "name"
            elif a.get("fs-cmsfilter-field") == "category":
                node["field"] = "types"
            elif "text-81" in cls:
                node["field"] = "statuses"
        self.stack.append(node)

    def handle_endtag(self, tag):
        if tag in VOID or not self.stack:
            return
        node = self.stack.pop()
        if node["item"] and self.cur is not None:
            self.items.append(self.cur)
            self.cur = None

    def handle_data(self, data):
        text = data.strip()
        if not text or self.cur is None:
            return
        field = next((s["field"] for s in reversed(self.stack) if s["field"]), None)
        if field == "name":
            self.cur["name"] += text
        elif field:
            self.cur[field].append(text)


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "KabuK-Platform-site/1.0 (+integrations list refresh)"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode("utf-8", "replace")


def main():
    files = sys.argv[1:]
    pages = ((open(f, encoding="utf-8").read() for f in files) if files
             else (fetch(f"{SOURCE}?baaa1da9_page={n}") for n in range(1, 20)))
    seen = {}
    for doc in pages:
        p = Cards()
        p.feed(doc)
        new = [i for i in p.items if i["name"] and i["name"] not in seen]
        for i in new:
            seen[i["name"]] = i
        if not new:
            break
    rows, review = [], []
    for i in sorted(seen.values(), key=lambda x: x["name"].lower()):
        statuses = [STATUS.get(s, s) for s in dict.fromkeys(i["statuses"])]
        types = [TYPE.get(s, s) for s in dict.fromkeys(i["types"])]
        row = {"name": i["name"], "type": types[0] if len(types) == 1 else "", "status": statuses[0] if len(statuses) == 1 else ""}
        if not row["type"] or not row["status"]:
            review.append({"name": i["name"], "types": i["types"], "statuses": i["statuses"]})
        rows.append(row)
    out = {
        "_source": SOURCE,
        "_retrieved": datetime.date.today().isoformat(),
        "_note": "Generated by tools/fetch_bakuun.py. Names, partner types and statuses are as published by Bakuun. 'status' is live | development; empty means Bakuun's listing is ambiguous (see _review).",
        "_review": review,
        "integrations": rows,
    }
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print(f"{len(rows)} integrations written to {os.path.relpath(OUT, ROOT)}; {len(review)} need review.")


if __name__ == "__main__":
    main()
